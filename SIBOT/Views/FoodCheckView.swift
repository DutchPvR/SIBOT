import SwiftData
import SwiftUI

struct FoodCheckView: View {
    @Environment(\.modelContext) private var modelContext

    @State private var query = ""
    @State private var aiVerdict: AIFoodVerdict?
    @State private var aiError: String?
    @State private var isAsking = false
    @State private var loggedMessage: String?

    private var results: [FoodItem] { FoodDatabase.shared.search(query) }
    private var trimmed: String { query.trimmingCharacters(in: .whitespacesAndNewlines) }

    var body: some View {
        NavigationStack {
            ZStack {
                Theme.background
                ScrollView {
                    VStack(spacing: 14) {
                        if trimmed.isEmpty {
                            hint
                        } else {
                            ForEach(results) { item in
                                resultCard(item)
                            }
                            askClaudeCard
                        }
                        if let loggedMessage {
                            Text(loggedMessage)
                                .font(.footnote)
                                .foregroundStyle(.secondary)
                        }
                    }
                    .padding()
                }
            }
            .navigationTitle("Can I eat this?")
            .searchable(text: $query, prompt: "Search a food, e.g. oatmeal")
            .onChange(of: query) { _, _ in
                aiVerdict = nil
                aiError = nil
                loggedMessage = nil
            }
        }
    }

    private var hint: some View {
        VStack(spacing: 8) {
            Text("🥦 🍚 🍗")
                .font(.system(size: 40))
            Text("Search a food to see if it fits the low-fermentation diet.")
                .multilineTextAlignment(.center)
                .foregroundStyle(.secondary)
            Text("Based on a starter list from the Cedars-Sinai diet. Double-check with your own guide or doctor.")
                .font(.footnote)
                .multilineTextAlignment(.center)
                .foregroundStyle(.tertiary)
        }
        .padding(.top, 40)
    }

    private func resultCard(_ item: FoodItem) -> some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack {
                Text(item.name)
                    .font(.system(.headline, design: .rounded))
                Spacer()
                StatusBadge(status: item.foodStatus)
            }
            Text(item.note)
                .font(.subheadline)
                .foregroundStyle(.secondary)
            logButton(text: item.name, status: item.foodStatus)
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .card()
    }

    private var askClaudeCard: some View {
        VStack(alignment: .leading, spacing: 10) {
            Text(results.isEmpty ? "Not on the list" : "Not what you meant?")
                .font(.system(.headline, design: .rounded))

            if let aiVerdict {
                HStack {
                    Text("AI guess")
                        .font(.caption.weight(.bold))
                        .padding(.horizontal, 8)
                        .padding(.vertical, 3)
                        .background(Theme.grape.opacity(0.15), in: Capsule())
                        .foregroundStyle(Theme.grape)
                    Spacer()
                    StatusBadge(status: aiVerdict.status)
                }
                Text(aiVerdict.reason)
                    .font(.subheadline)
                    .foregroundStyle(.secondary)
                Text("Generated by an AI model, not from your food list. Verify if it matters.")
                    .font(.caption)
                    .foregroundStyle(.tertiary)
                logButton(text: trimmed, status: aiVerdict.status)
            } else {
                if let aiError {
                    Text(aiError)
                        .font(.subheadline)
                        .foregroundStyle(Theme.pink)
                }
                Button {
                    ask()
                } label: {
                    HStack {
                        if isAsking { ProgressView() }
                        Text(isAsking ? "Asking AI…" : "Ask AI about “\(trimmed)”")
                    }
                    .frame(maxWidth: .infinity)
                }
                .buttonStyle(.borderedProminent)
                .tint(Theme.grape)
                .disabled(isAsking)
            }
        }
        .frame(maxWidth: .infinity, alignment: .leading)
        .card()
    }

    private func logButton(text: String, status: FoodStatus) -> some View {
        Button {
            modelContext.insert(MealEntry(text: text, status: status))
            loggedMessage = "Logged “\(text)”."
        } label: {
            Label("Log it", systemImage: "plus.circle.fill")
                .font(.subheadline.weight(.semibold))
        }
        .tint(Theme.pink)
    }

    private func ask() {
        isAsking = true
        aiError = nil
        let food = trimmed
        Task {
            do {
                aiVerdict = try await AIFoodChecker.check(food)
            } catch {
                aiError = error.localizedDescription
            }
            isAsking = false
        }
    }
}
